//! The runtime entry points that generated code calls, and the runner that starts a program.
//! Each is `extern "C"` and takes the machine record first.

use super::heap::{self, kind, Word};
use super::{Machine, Program, ARG_SLOTS};
use crate::native::codegen::frame;

// The generated code takes the machine record by pointer and reads only its leading words (see
// `Machine`); the heap inside it is never touched from assembly.
#[allow(improper_ctypes)]
extern "C" {
    /// The entry of a program: runs the closure in %rsi with the arguments on the stack. Returns 0
    /// when the continuation (the stop frame) is reached, 1 when an exception unwound to it.
    fn hsc_enter(m: *mut Machine, closure: Word) -> i32;
    /// Evaluates the object in %rsi to weak head normal form, as a nested run. Returns as `hsc_enter`.
    fn hsc_enter_eval(m: *mut Machine, obj: Word) -> i32;
    /// The continuation that ends a run: its address marks the bottom of a stack segment.
    fn hsc_stop_ret();
    /// The apply frame's return address (the apply of a result to the arguments above it).
    fn hsc_apply_ret();
}

/// The tables the code generator emits (`native::codegen::Gen::program`), as the runtime reads them.
#[repr(C)]
pub struct NativeTable {
    /// One pair per global: `[kind_arity: i32, code_off: i32]` relative to `globals`.
    pub globals: *const [i32; 2],
    pub nglobals: u64,
    /// Constructor names: `[byte_off: u32, len: u32]` relative to `con_names`.
    pub con_names: *const [u32; 2],
    pub ncons: u64,
    /// Primitive names: `[byte_off: u32, len: u32]` relative to `prim_names`.
    pub prim_names: *const [u32; 2],
    pub nprims: u64,
    /// The index of `Main.main` among the globals.
    pub main_index: u64,
    /// The bodies in address order: `[code_off: i32, name_off: u32, name_len: u32]` relative to `bodies`.
    pub bodies: *const [u32; 3],
    pub nbodies: u64,
    /// The bindings the runtime uses (`native::RTS_GLOBALS`): `[name_off: u32, name_len: u32, global_idx: u32]` relative to `rts`.
    pub rts: *const [u32; 3],
    pub nrts: u64,
    /// Selector thunk table: `[code_off: i32, con_id: u32, field_word: u32]` relative to `selectors`.
    pub selectors: *const [u32; 3],
    pub nselectors: u64,
}

/// The static name written at a relative byte offset and length in the program's read-only data.
pub(super) unsafe fn name_at(p: *const [u32; 2], i: usize) -> &'static str {
    let [off, len] = *p.add(i);
    let ptr = (p as *const u8).add(off as usize);
    std::str::from_utf8(std::slice::from_raw_parts(ptr, len as usize)).unwrap_or("")
}

/// Runs a compiled program: its global closures are allocated, then `Main.main` is applied to the
/// state token. Returns the exit status.
///
/// # Safety
/// `table` must point to the tables of a program generated by `native::codegen`.
/// The body table and its name bytes must remain immutable for the lifetime of the process.
pub unsafe fn run(table: *const NativeTable) -> i32 {
    let t = &*table;
    let globals_base = t.globals as usize;
    let nglobals = t.nglobals as usize;
    let mut m = Machine::new(Program {
        nglobals,
        con_names: t.con_names,
        ncons: t.ncons as usize,
        prim_names: t.prim_names,
        nprims: t.nprims as usize,
    });
    m.bodies = DiagnosticBodies::from_raw_parts(t.bodies, t.nbodies as usize);
    if !t.selectors.is_null() && t.nselectors > 0 {
        m.selectors_raw = (t.selectors, t.nselectors as usize);
    }
    // The global closures: functions of their arity, or thunks, allocated on the heap.
    let mut gvec: Vec<Word> = Vec::with_capacity(nglobals);
    for i in 0..nglobals {
        let [kind_arity, off] = *t.globals.add(i);
        let code = globals_base.wrapping_add_signed(off as isize);
        let p = m.alloc_no_gc(2);
        if kind_arity > 0 {
            m.heap_set(p, heap::header(kind::FUN, 1, kind_arity as u32));
        } else {
            m.heap_set(p, heap::header(kind::THUNK, 1, 0));
        }
        m.heap_set(p + 8, code as Word);
        gvec.push(p);
    }
    m.rts_globals.reserve(t.nrts as usize);
    let rts_base = t.rts as *const u8;
    for i in 0..t.nrts as usize {
        let [off, len, idx] = *t.rts.add(i);
        let name = std::str::from_utf8(std::slice::from_raw_parts(rts_base.add(off as usize), len as usize)).unwrap_or("");
        m.rts_globals.insert(name, idx as usize);
    }
    m.globals = gvec.as_mut_ptr();
    m.global_vec = gvec;
    // The stack: the state token, then the stop frame above it. The stop frame records no outer stack.
    let stop = hsc_stop_ret as usize as Word;
    let a = m.sp - 24;
    m.stack_store(a, stop);
    m.stack_store(a + 8, 0);
    m.stack_store(a + 16, 0);
    m.stack_store(a - 8, 0);
    m.sp = a - 8;
    m.nargs = 1;
    let main = m.global_vec[t.main_index as usize];
    let status = hsc_enter(&mut *m as *mut Machine, main);
    // The runtime's apply-frame address is referenced for the over-application path.
    let _ = hsc_apply_ret as usize;
    // The process exits immediately after `hsc_native_main`; skip unmapping the stack/heap.
    std::mem::forget(m);
    status
}

/// Entry point called by the program's `main`.
#[no_mangle]
pub extern "C" fn hsc_native_main(table: *const NativeTable) -> i32 {
    // Nested evaluations from the runtime (a primitive forcing an argument) use the native stack, and
    // a chain of lazy values can be deep, so the program runs on a thread with a large stack, as the
    // interpreter does.
    let t = table as usize;
    std::thread::Builder::new()
        .stack_size(4 << 30)
        .spawn(move || {
            // SAFETY: the object's `main` passes the table generated for this program.
            unsafe { run(t as *const NativeTable) }
        })
        .map(|h| {
            // This thread only waits: signals go to the program's threads.
            crate::signals::block_all();
            h.join().unwrap_or(1)
        })
        .unwrap_or(1)
}

impl Machine {
    /// The value of an object, evaluated: a runtime call for a thunk runs it to weak head normal form
    /// on this stack, above the current frame. Returns None when the evaluation raised (the exception
    /// is in `exc`).
    pub fn force(&mut self, p: Word) -> Option<Word> {
        let mut v = p;
        loop {
            let h = self.heap_get(v, 0);
            match heap::kind_of(h) {
                kind::IND => v = self.heap_get(v, 1),
                kind::THUNK => break,
                _ => return Some(v),
            }
        }
        // The stop frame [stop][outer sp][outer top] sits below the current frames; the walk of the
        // collector continues from the outer position through it.
        let outer_sp = self.sp;
        let outer_top = self.top;
        let stop = hsc_stop_ret as usize as Word;
        let a = outer_sp - 24;
        self.stack_store(a, stop);
        self.stack_store(a + 8, outer_sp);
        self.stack_store(a + 16, outer_top);
        self.sp = a;
        // The nested run uses the argument slots: the caller's arguments are saved (and are roots).
        self.saved_args.push(self.args);
        // SAFETY: the entry runs generated code on this machine's stack.
        let status = unsafe { hsc_enter_eval(self as *mut Machine, v) };
        self.args = self.saved_args.pop().unwrap_or([0; ARG_SLOTS]);
        self.sp = outer_sp;
        self.top = outer_top;
        if status == 0 {
            let r = self.r1;
            if matches!(heap::kind_of(self.heap_get(r, 0)), kind::THUNK | kind::IND) {
                return self.force(r);
            }
            Some(r)
        } else {
            self.prim_failed = true;
            None
        }
    }
}

/// The collector, called when the heap is full: `words` are needed.
#[no_mangle]
pub extern "C" fn hsc_gc(m: *mut Machine, words: u64) {
    // SAFETY: generated code passes the machine record.
    let m = unsafe { &mut *m };
    m.collect(words as usize);
}

/// A preemption point at a function's entry (see `conc::safe_point`): answers 1 with an
/// exception for this thread raised in `exc`, else 0.
#[no_mangle]
pub extern "C" fn hsc_yield(mp: *mut Machine) -> u64 {
    super::conc::safe_point(mp) as u64
}

/// A primitive operation: `id` names it in the program's table; its arguments are in the record.
/// Returns the result, or 0 with the exception raised in `exc`.
#[no_mangle]
pub extern "C" fn hsc_prim(mp: *mut Machine, id: u64, nargs: u64) -> Word {
    // SAFETY: generated code passes the machine record.
    let nargs = (nargs as usize).min(ARG_SLOTS);
    let prev_nargs = unsafe {
        let m = &mut *mp;
        let prev = m.prim_nargs;
        m.prim_nargs = nargs;
        prev
    };
    // At the end of a time slice another thread runs first; an exception thrown to this one
    // meanwhile is raised in place of the primitive.
    if super::conc::safe_point(mp) {
        // SAFETY: machine is valid for the running thread.
        unsafe { (*mp).prim_nargs = prev_nargs };
        return 0;
    }
    // SAFETY: re-derive after safe_point (which may have switched coroutines and back).
    let m = unsafe { &mut *mp };
    let idx = id as usize;
    let dispatch = match m.prim_dispatch[idx] {
        super::PrimDispatch::Unclassified => m.classify_prim(idx),
        d => d,
    };
    if let super::PrimDispatch::Conc(op) = dispatch {
        let r = op.run_fast(mp);
        // SAFETY: re-derive after possible coroutine switch.
        unsafe { (*mp).prim_nargs = prev_nargs };
        return r;
    }
    // A primitive builds its result from several allocations, holding the earlier objects in Rust
    // locals; a collection between them would move those objects. So the collection happens before
    // it runs, and the room it needs is reserved then.
    m.reserve(PRIM_SLACK);
    let r = match dispatch {
        super::PrimDispatch::Int(op) => op.run(m),
        super::PrimDispatch::Integer(op) => op.run(m),
        super::PrimDispatch::Ordinary(name) => super::prims::run_ordinary(m, idx, name, nargs),
        super::PrimDispatch::CCall => super::prims::run_ccall(m, idx, nargs),
        super::PrimDispatch::Conc(_) | super::PrimDispatch::Unclassified => unreachable!(),
    };
    // SAFETY: re-derive in case the primitive switched coroutines.
    let m = unsafe { &mut *mp };
    m.prim_nargs = prev_nargs;
    // Generated code takes a primitive's result as a value: a thunk (a result that is a variable of
    // the program, not yet evaluated) is evaluated here first.
    if r != 0 && matches!(heap::kind_of(m.heap_get(r, 0)), kind::THUNK | kind::IND) {
        return m.force(r).unwrap_or(0);
    }
    r
}

/// The words a primitive may allocate without a collection (see `hsc_prim`).
const PRIM_SLACK: usize = 16384;

/// Application to a value that is not a function of the right arity: the slow path. Returns the
/// action for the caller: 1 enter `m.code`, 2 return `m.r1`, 3 apply again to `m.nargs`, 4 raise.
#[no_mangle]
pub extern "C" fn hsc_apply_slow(m: *mut Machine) -> i32 {
    // SAFETY: generated code passes the machine record.
    let m = unsafe { &mut *m };
    let n = m.nargs as usize;
    let f = m.r1;
    let h = m.heap_get(f, 0);
    match heap::kind_of(h) {
        kind::FUN => {
            let arity = heap::aux_of(h) as usize;
            let code = m.heap_get(f, 1);
            if arity == n {
                m.code = code;
                1
            } else if arity < n {
                // Over-application: the first `arity` arguments go to the function; the rest wait in an
                // apply frame [apply return][count][arguments], which sits above the callee's arguments.
                let rest = n - arity;
                let base = m.sp - 16;
                for i in 0..arity {
                    let v = m.stack_load(m.sp + 8 * i as Word);
                    m.stack_store(base + 8 * i as Word, v);
                }
                m.stack_store(base + 8 * arity as Word, hsc_apply_ret as usize as Word);
                m.stack_store(base + 8 * arity as Word + 8, rest as Word);
                m.sp = base;
                m.code = code;
                1
            } else {
                // Under-application: a partial application object, and the arguments are popped.
                let words = 2 + n;
                let pap = m.alloc(words);
                // The allocation may have collected: the function is read again from R1 (a root),
                // since `f` is the address it had before.
                let f = m.r1;
                m.heap_set(pap, heap::header(super::super::native::codegen::PAP, (n + 1) as u32, n as u32));
                m.heap_set(pap + 8, f);
                for i in 0..n {
                    let v = m.stack_load(m.sp + 8 * i as Word);
                    m.heap_set(pap + 16 + 8 * i as Word, v);
                }
                m.sp += 8 * n as Word;
                m.r1 = pap;
                2
            }
        }
        kind::PAP => {
            // The held arguments go below the new ones; the function is applied to all of them.
            let held = heap::aux_of(h) as usize;
            let fun = m.heap_get(f, 1);
            let base = m.sp - 8 * held as Word;
            for i in 0..held {
                let v = m.heap_get(f, 2 + i);
                m.stack_store(base + 8 * i as Word, v);
            }
            m.sp = base;
            m.nargs = (held + n) as Word;
            m.r1 = fun;
            3
        }
        _ => {
            m.exc = m.error_value("application of a non-function");
            4
        }
    }
}

/// Raises the pending exception: unwinds the stack to the nearest catch frame, or to the stop frame.
/// Returns 1 with the handler in `r1` and its two arguments on the stack, or 0 when uncaught.
#[no_mangle]
pub extern "C" fn hsc_unwind(m: *mut Machine) -> i32 {
    // SAFETY: generated code passes the machine record.
    let m = unsafe { &mut *m };
    let mut p = m.sp + 8 * crate::native::codegen::frame::words(m.top);
    loop {
        let ret = m.stack_load(p);
        let fkind = m.stack_load(ret - 16);
        p += 8;
        match fkind {
            frame::STOP => {
                m.sp = p - 8;
                return 0;
            }
            frame::BODY => {
                let size = crate::native::codegen::frame::words(m.stack_load(ret - 8));
                p += 8 * size;
            }
            frame::UPDATE => {
                // The thunk is not updated: it is evaluated again if forced again.
                let t = m.stack_load(p);
                let h = m.heap_get(t, 0);
                m.heap_set(t, h & 0xffff_ffff);
                p += 8;
            }
            frame::MASK => {
                let saved = m.stack_load(p);
                super::conc::unwind_mask(m, saved);
                p += 8;
            }
            frame::CATCH => {
                // The catch frame [return][handler] is popped; the handler gets the exception and the
                // state token, as its two arguments, in its place. It runs masked: when the thread was
                // not, a mask frame takes the catch frame's place, below the arguments.
                let handler = m.stack_load(p);
                let exc = m.exc;
                let new_sp = if super::conc::mask_for_handler(m, p - 8) { p - 24 } else { p - 8 };
                m.stack_store(new_sp, exc);
                m.stack_store(new_sp + 8, 0);
                m.sp = new_sp;
                m.r1 = handler;
                m.nargs = 2;
                return 1;
            }
            frame::APPLY => {
                let n = m.stack_load(p);
                p += 8 * (1 + n);
            }
            other => panic!("internal: unknown frame {other} while unwinding"),
        }
    }
}

/// A pattern-match or other failure of compiled code: the exception is built for the position.
#[no_mangle]
pub extern "C" fn hsc_fail(m: *mut Machine, ptr: *const u8, len: u64) {
    // SAFETY: generated code passes the machine record and the message's bytes.
    let m = unsafe { &mut *m };
    let text = unsafe { std::slice::from_raw_parts(ptr, len as usize) };
    let msg = String::from_utf8_lossy(text).into_owned();
    m.exc = m.error_value(&msg);
}

/// Whether a scrutinee matches a literal pattern (its text and kind, see `native::codegen::lit_text`).
#[no_mangle]
pub extern "C" fn hsc_lit_matches(m: *mut Machine, scrut: Word, ptr: *const u8, len: u64, kind_: u64) -> i32 {
    // SAFETY: generated code passes the machine record and the pattern's text.
    let m = unsafe { &mut *m };
    let text = String::from_utf8_lossy(unsafe { std::slice::from_raw_parts(ptr, len as usize) }).into_owned();
    m.literal_matches(scrut, &text, kind_) as i32
}

/// A computation that depends on itself: the NonTermination exception.
#[no_mangle]
pub extern "C" fn hsc_nontermination(m: *mut Machine) {
    // SAFETY: generated code passes the machine record.
    let m = unsafe { &mut *m };
    m.exc = m.error_value("<<loop>>");
}

/// A literal built by the runtime: a string (a list of characters), an `Integer` (kind 1), a
/// rational (kind 2) or an `Addr#` (kind 3). Allocates; the result is returned.
#[no_mangle]
pub extern "C" fn hsc_mk_literal(m: *mut Machine, ptr: *const u8, len: u64, kind_: u64) -> Word {
    // SAFETY: generated code passes the machine record and the literal's text.
    let m = unsafe { &mut *m };
    let bytes = unsafe { std::slice::from_raw_parts(ptr, len as usize) };
    if kind_ == 3 {
        return super::prims::addr_literal(m, bytes);
    }
    let text = String::from_utf8_lossy(bytes).into_owned();
    super::prims::literal(m, &text, kind_)
}

impl Machine {
    /// Applies a function to arguments on this stack, as a nested run, and answers its result (in
    /// weak head normal form), or None when it raised. The arguments are saved and restored around it
    /// like those of a primitive.
    pub fn apply_nested(&mut self, f: Word, args: &[Word]) -> Option<Word> {
        let outer_sp = self.sp;
        let outer_top = self.top;
        let stop = hsc_stop_ret as usize as Word;
        // [arguments][stop frame]: the stop frame records the outer stack.
        let a = outer_sp - 24;
        self.stack_store(a, stop);
        self.stack_store(a + 8, outer_sp);
        self.stack_store(a + 16, outer_top);
        let n = args.len();
        let base = a - 8 * n as Word;
        for (i, v) in args.iter().enumerate() {
            self.stack_store(base + 8 * i as Word, *v);
        }
        self.sp = base;
        self.nargs = n as Word;
        self.saved_args.push(self.args);
        // SAFETY: the entry runs generated code on this machine's stack.
        let status = unsafe { hsc_enter(self as *mut Machine, f) };
        self.args = self.saved_args.pop().unwrap_or([0; super::ARG_SLOTS]);
        self.sp = outer_sp;
        self.top = outer_top;
        if status == 0 {
            Some(self.r1)
        } else {
            self.prim_failed = true;
            None
        }
    }
}

/// Diagnostic metadata emitted in the executable. Names are decoded only when requested,
/// rather than allocating a String for every body during ordinary startup.
#[derive(Default)]
pub struct DiagnosticBodies {
    base: usize,
    rows: &'static [[u32; 3]],
}

impl DiagnosticBodies {
    /// Borrows the executable's relative body table without copying its names.
    ///
    /// # Safety
    /// For nonzero `len`, `rows` must be aligned and readable for `len` triples `[code_off,
    /// name_off, name_len]` relative to `rows`, sorted by resolved code address. The triples and
    /// every nonempty referenced byte range must be immutable and valid for the process lifetime.
    unsafe fn from_raw_parts(rows: *const [u32; 3], len: usize) -> Self {
        if len == 0 {
            return Self::default();
        }
        Self { base: rows as usize, rows: std::slice::from_raw_parts(rows, len) }
    }

    fn name(&self, addr: Word) -> String {
        let base = self.base;
        match self.rows.partition_point(|row| (base.wrapping_add_signed((row[0] as i32) as isize) as Word) <= addr) {
            0 => String::from("?"),
            i => {
                let [_, off, len] = self.rows[i - 1];
                if len == 0 {
                    return String::new();
                }
                // SAFETY: the constructor requires these bytes to remain valid and immutable.
                let bytes = unsafe { std::slice::from_raw_parts((base as *const u8).add(off as usize), len as usize) };
                String::from_utf8_lossy(bytes).into_owned()
            }
        }
    }
}

impl Machine {
    /// The name of the body containing a code address (for diagnostics).
    pub fn body_name(&self, addr: Word) -> String {
        self.bodies.name(addr)
    }
}

#[cfg(test)]
mod diagnostic_body_tests {
    use super::DiagnosticBodies;

    #[test]
    fn empty_tables_accept_null_and_return_unknown() {
        let bodies = unsafe { DiagnosticBodies::from_raw_parts(std::ptr::null(), 0) };
        assert_eq!(bodies.name(0), "?");
        assert_eq!(bodies.name(u64::MAX), "?");
        assert_eq!(DiagnosticBodies::default().name(100), "?");
    }

    #[test]
    fn names_follow_address_boundaries_and_decode_only_selected_bytes() {
        #[repr(C, align(4))]
        struct Table {
            rows: [[u32; 3]; 3],
            bytes: [u8; 16],
        }
        let first = "main \u{03bb}".as_bytes();
        let invalid = b"bad\xffname";
        let mut buf = [0u8; 16];
        buf[..first.len()].copy_from_slice(first);
        buf[first.len()..first.len() + invalid.len()].copy_from_slice(invalid);
        let header_bytes = 3 * 12;
        let tbl = Box::leak(Box::new(Table {
            rows: [
                [(-100i32) as u32, header_bytes as u32, first.len() as u32],
                [(-90i32) as u32, (header_bytes + first.len()) as u32, invalid.len() as u32],
                [(-80i32) as u32, 0, 0],
            ],
            bytes: buf,
        }));
        let base = tbl.rows.as_ptr() as usize;
        let addr = |off: isize| base.wrapping_add_signed(off) as u64;
        let bodies = unsafe { DiagnosticBodies::from_raw_parts(tbl.rows.as_ptr(), tbl.rows.len()) };
        assert_eq!(bodies.name(addr(-101)), "?");
        assert_eq!(bodies.name(addr(-100)), "main \u{03bb}");
        assert_eq!(bodies.name(addr(-91)), "main \u{03bb}");
        assert_eq!(bodies.name(addr(-90)), "bad\u{FFFD}name");
        assert_eq!(bodies.name(addr(-81)), "bad\u{FFFD}name");
        assert_eq!(bodies.name(addr(-80)), "");
        assert_eq!(bodies.name(u64::MAX), "");
    }
}
