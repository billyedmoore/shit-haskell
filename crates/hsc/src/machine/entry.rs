//! The runtime entry points that generated code calls, and the runner that starts a program.
//! Each is `extern "C"` and takes the machine record first.

use super::heap::{self, kind, Word};
use super::{Machine, Program, ARG_SLOTS};
use crate::native::codegen::frame;

extern "C" {
    /// The entry of a program: runs the closure in %rsi with the arguments on the stack. Returns 0
    /// when the continuation (the stop frame) is reached, 1 when an exception unwound to it.
    fn hsc_enter(m: *mut Machine, closure: Word) -> i32;
    /// Evaluates the object in %rsi to weak head normal form, as a nested run. Returns as `hsc_enter`.
    fn hsc_enter_eval(m: *mut Machine, obj: Word) -> i32;
    /// The continuation that ends a run: its address marks the bottom of a stack segment.
    fn hsc_stop_ret();
    /// The apply frame's return address (the apply of a result to the arguments above it).
    fn hsc_apply_ret();
}

/// The tables the code generator emits (`native::codegen::Gen::program`), as the runtime reads them.
#[repr(C)]
pub struct NativeTable {
    /// One pair per global: its kind (the arity, or -1 for a thunk) and its code address.
    pub globals: *const [i64; 2],
    pub nglobals: u64,
    /// Constructor names: pointer and length pairs.
    pub con_names: *const [u64; 2],
    pub ncons: u64,
    /// Primitive names: pointer and length pairs.
    pub prim_names: *const [u64; 2],
    pub nprims: u64,
    /// The index of `Main.main` among the globals.
    pub main_index: u64,
    /// The bodies in address order: entry address, name pointer and length.
    pub bodies: *const [u64; 3],
    pub nbodies: u64,
}

/// The name written at a pointer and length.
unsafe fn name_at(p: *const [u64; 2], i: usize) -> String {
    let [ptr, len] = *p.add(i);
    String::from_utf8_lossy(std::slice::from_raw_parts(ptr as *const u8, len as usize)).into_owned()
}

/// Runs a compiled program: its global closures are allocated, then `Main.main` is applied to the
/// state token. Returns the exit status.
///
/// # Safety
/// `table` must point to the tables of a program generated by `native::codegen`.
pub unsafe fn run(table: *const NativeTable) -> i32 {
    let t = &*table;
    let cons: Vec<String> = (0..t.ncons as usize).map(|i| name_at(t.con_names, i)).collect();
    let prims: Vec<String> = (0..t.nprims as usize).map(|i| name_at(t.prim_names, i)).collect();
    let globals: Vec<(i64, usize)> = (0..t.nglobals as usize)
        .map(|i| {
            let [kind, code] = *t.globals.add(i);
            (kind, code as usize)
        })
        .collect();
    let mut m = Machine::new(Program { globals, con_names: cons, prim_names: prims });
    m.bodies = (0..t.nbodies as usize)
        .map(|i| {
            let [addr, ptr, len] = *t.bodies.add(i);
            let name = String::from_utf8_lossy(std::slice::from_raw_parts(ptr as *const u8, len as usize)).into_owned();
            (addr, name)
        })
        .collect();
    // The global closures: functions of their arity, or thunks, allocated on the heap.
    let mut gvec: Vec<Word> = Vec::with_capacity(t.nglobals as usize);
    for (kind_arity, code) in m.prog.globals.clone() {
        let p = m.alloc_no_gc(2);
        if kind_arity > 0 {
            m.heap_set(p, heap::header(kind::FUN, 1, kind_arity as u32));
        } else {
            m.heap_set(p, heap::header(kind::THUNK, 1, 0));
        }
        m.heap_set(p + 8, code as Word);
        gvec.push(p);
    }
    m.globals = gvec.as_mut_ptr();
    m.global_vec = gvec;
    // The stack: the state token, then the stop frame above it. The stop frame records no outer stack.
    let stop = hsc_stop_ret as usize as Word;
    let a = m.sp - 24;
    m.stack_store(a, stop);
    m.stack_store(a + 8, 0);
    m.stack_store(a + 16, 0);
    m.stack_store(a - 8, 0);
    m.sp = a - 8;
    m.nargs = 1;
    let main = m.global_vec[t.main_index as usize];
    let status = hsc_enter(&mut *m as *mut Machine, main);
    // The runtime's apply-frame address is referenced for the over-application path.
    let _ = hsc_apply_ret as usize;
    status
}

/// Entry point called by the program's `main`.
#[no_mangle]
pub extern "C" fn hsc_native_main(table: *const NativeTable) -> i32 {
    // SAFETY: the object's `main` passes the table generated for this program.
    unsafe { run(table) }
}

impl Machine {
    /// The value of an object, evaluated: a runtime call for a thunk runs it to weak head normal form
    /// on this stack, above the current frame. Returns None when the evaluation raised (the exception
    /// is in `exc`).
    pub fn force(&mut self, p: Word) -> Option<Word> {
        let mut v = p;
        loop {
            let h = self.heap_get(v, 0);
            match heap::kind_of(h) {
                kind::IND => v = self.heap_get(v, 1),
                kind::THUNK => break,
                _ => return Some(v),
            }
        }
        // The stop frame [stop][outer sp][outer top] sits below the current frames; the walk of the
        // collector continues from the outer position through it.
        let outer_sp = self.sp;
        let outer_top = self.top;
        let stop = hsc_stop_ret as usize as Word;
        let a = outer_sp - 24;
        self.stack_store(a, stop);
        self.stack_store(a + 8, outer_sp);
        self.stack_store(a + 16, outer_top);
        self.sp = a;
        // The nested run uses the argument slots: the caller's arguments are saved (and are roots).
        self.saved_args.push(self.args);
        // SAFETY: the entry runs generated code on this machine's stack.
        let status = unsafe { hsc_enter_eval(self as *mut Machine, v) };
        self.args = self.saved_args.pop().unwrap_or([0; ARG_SLOTS]);
        self.sp = outer_sp;
        self.top = outer_top;
        if status == 0 {
            Some(self.r1)
        } else {
            self.prim_failed = true;
            None
        }
    }
}

/// The collector, called when the heap is full: `words` are needed.
#[no_mangle]
pub extern "C" fn hsc_gc(m: *mut Machine, words: u64) {
    // SAFETY: generated code passes the machine record.
    let m = unsafe { &mut *m };
    m.collect(words as usize);
}

/// A primitive operation: `id` names it in the program's table; its arguments are in the record.
/// Returns the result, or 0 with the exception raised in `exc`.
#[no_mangle]
pub extern "C" fn hsc_prim(m: *mut Machine, id: u64, nargs: u64) -> Word {
    // SAFETY: generated code passes the machine record.
    let m = unsafe { &mut *m };
    let name = m.prog.prim_names[id as usize].clone();
    // A primitive builds its result from several allocations, holding the earlier objects in Rust
    // locals; a collection between them would move those objects. So the collection happens before
    // it runs, and the room it needs is reserved then.
    m.reserve(PRIM_SLACK);
    super::prims::run(m, &name, (nargs as usize).min(ARG_SLOTS))
}

/// The words a primitive may allocate without a collection (see `hsc_prim`).
const PRIM_SLACK: usize = 16384;

/// Application to a value that is not a function of the right arity: the slow path. Returns the
/// action for the caller: 1 enter `m.code`, 2 return `m.r1`, 3 apply again to `m.nargs`, 4 raise.
#[no_mangle]
pub extern "C" fn hsc_apply_slow(m: *mut Machine) -> i32 {
    // SAFETY: generated code passes the machine record.
    let m = unsafe { &mut *m };
    let n = m.nargs as usize;
    let f = m.r1;
    let h = m.heap_get(f, 0);
    match heap::kind_of(h) {
        kind::FUN => {
            let arity = heap::aux_of(h) as usize;
            let code = m.heap_get(f, 1);
            if arity == n {
                m.code = code;
                1
            } else if arity < n {
                // Over-application: the first `arity` arguments go to the function; the rest wait in an
                // apply frame [apply return][count][arguments], which sits above the callee's arguments.
                let rest = n - arity;
                let base = m.sp - 16;
                for i in 0..arity {
                    let v = m.stack_load(m.sp + 8 * i as Word);
                    m.stack_store(base + 8 * i as Word, v);
                }
                m.stack_store(base + 8 * arity as Word, hsc_apply_ret as usize as Word);
                m.stack_store(base + 8 * arity as Word + 8, rest as Word);
                m.sp = base;
                m.code = code;
                1
            } else {
                // Under-application: a partial application object, and the arguments are popped.
                let words = 2 + n;
                let pap = m.alloc(words);
                m.heap_set(pap, heap::header(super::super::native::codegen::PAP, (n + 1) as u32, n as u32));
                m.heap_set(pap + 8, f);
                for i in 0..n {
                    let v = m.stack_load(m.sp + 8 * i as Word);
                    m.heap_set(pap + 16 + 8 * i as Word, v);
                }
                m.sp += 8 * n as Word;
                m.r1 = pap;
                2
            }
        }
        kind::PAP => {
            // The held arguments go below the new ones; the function is applied to all of them.
            let held = heap::aux_of(h) as usize;
            let fun = m.heap_get(f, 1);
            let base = m.sp - 8 * held as Word;
            for i in 0..held {
                let v = m.heap_get(f, 2 + i);
                m.stack_store(base + 8 * i as Word, v);
            }
            m.sp = base;
            m.nargs = (held + n) as Word;
            m.r1 = fun;
            3
        }
        _ => {
            m.exc = m.error_value("application of a non-function");
            4
        }
    }
}

/// Raises the pending exception: unwinds the stack to the nearest catch frame, or to the stop frame.
/// Returns 1 with the handler in `r1` and its two arguments on the stack, or 0 when uncaught.
#[no_mangle]
pub extern "C" fn hsc_unwind(m: *mut Machine) -> i32 {
    // SAFETY: generated code passes the machine record.
    let m = unsafe { &mut *m };
    let mut p = m.sp + 8 * m.top;
    loop {
        let ret = m.stack_load(p);
        let fkind = m.stack_load(ret - 16);
        p += 8;
        match fkind {
            frame::STOP => {
                m.sp = p - 8;
                return 0;
            }
            frame::BODY => {
                let size = m.stack_load(ret - 8);
                p += 8 * size;
            }
            frame::UPDATE => {
                // The thunk is not updated: it is evaluated again if forced again.
                let t = m.stack_load(p);
                let h = m.heap_get(t, 0);
                m.heap_set(t, h & 0xffff_ffff);
                p += 8;
            }
            frame::CATCH => {
                // The catch frame [return][handler] is popped; the handler gets the exception and the
                // state token, as its two arguments, in its place.
                let handler = m.stack_load(p);
                let exc = m.exc;
                let new_sp = p - 8;
                m.stack_store(new_sp, exc);
                m.stack_store(new_sp + 8, 0);
                m.sp = new_sp;
                m.r1 = handler;
                m.nargs = 2;
                return 1;
            }
            frame::APPLY => {
                let n = m.stack_load(p);
                p += 8 * (1 + n);
            }
            other => panic!("internal: unknown frame {other} while unwinding"),
        }
    }
}

/// A pattern-match or other failure of compiled code: the exception is built for the position.
#[no_mangle]
pub extern "C" fn hsc_fail(m: *mut Machine, ptr: *const u8, len: u64) {
    // SAFETY: generated code passes the machine record and the message's bytes.
    let m = unsafe { &mut *m };
    let text = unsafe { std::slice::from_raw_parts(ptr, len as usize) };
    let msg = String::from_utf8_lossy(text).into_owned();
    m.exc = m.error_value(&msg);
}

/// Whether a scrutinee matches a literal pattern (its text and kind, see `native::codegen::lit_text`).
#[no_mangle]
pub extern "C" fn hsc_lit_matches(m: *mut Machine, scrut: Word, ptr: *const u8, len: u64, kind_: u64) -> i32 {
    // SAFETY: generated code passes the machine record and the pattern's text.
    let m = unsafe { &mut *m };
    let text = String::from_utf8_lossy(unsafe { std::slice::from_raw_parts(ptr, len as usize) }).into_owned();
    m.literal_matches(scrut, &text, kind_) as i32
}

/// A computation that depends on itself: the NonTermination exception.
#[no_mangle]
pub extern "C" fn hsc_nontermination(m: *mut Machine) {
    // SAFETY: generated code passes the machine record.
    let m = unsafe { &mut *m };
    m.exc = m.error_value("<<loop>>");
}

/// A literal built by the runtime: a string (a list of characters), an `Integer` (kind 1), a
/// rational (kind 2) or an `Addr#` (kind 3). Allocates; the result is returned.
#[no_mangle]
pub extern "C" fn hsc_mk_literal(m: *mut Machine, ptr: *const u8, len: u64, kind_: u64) -> Word {
    // SAFETY: generated code passes the machine record and the literal's text.
    let m = unsafe { &mut *m };
    let text = String::from_utf8_lossy(unsafe { std::slice::from_raw_parts(ptr, len as usize) }).into_owned();
    super::prims::literal(m, &text, kind_)
}

impl Machine {
    /// Applies a function to arguments on this stack, as a nested run, and answers its result (in
    /// weak head normal form), or None when it raised. The arguments are saved and restored around it
    /// like those of a primitive.
    pub fn apply_nested(&mut self, f: Word, args: &[Word]) -> Option<Word> {
        let outer_sp = self.sp;
        let outer_top = self.top;
        let stop = hsc_stop_ret as usize as Word;
        // [arguments][stop frame]: the stop frame records the outer stack.
        let a = outer_sp - 24;
        self.stack_store(a, stop);
        self.stack_store(a + 8, outer_sp);
        self.stack_store(a + 16, outer_top);
        let n = args.len();
        let base = a - 8 * n as Word;
        for (i, v) in args.iter().enumerate() {
            self.stack_store(base + 8 * i as Word, *v);
        }
        self.sp = base;
        self.nargs = n as Word;
        self.saved_args.push(self.args);
        // SAFETY: the entry runs generated code on this machine's stack.
        let status = unsafe { hsc_enter(self as *mut Machine, f) };
        self.args = self.saved_args.pop().unwrap_or([0; super::ARG_SLOTS]);
        self.sp = outer_sp;
        self.top = outer_top;
        if status == 0 {
            Some(self.r1)
        } else {
            self.prim_failed = true;
            None
        }
    }
}

impl Machine {
    /// The name of the body containing a code address (for diagnostics).
    pub fn body_name(&self, addr: Word) -> String {
        match self.bodies.partition_point(|(a, _)| *a <= addr) {
            0 => String::from("?"),
            i => self.bodies[i - 1].1.clone(),
        }
    }
}

