#define ALIGNMENT_CHAR 1
#define ALIGNMENT_DOUBLE 8
#define ALIGNMENT_FLOAT 4
#define ALIGNMENT_INT 4
#define ALIGNMENT_INT16_T 2
#define ALIGNMENT_INT32_T 4
